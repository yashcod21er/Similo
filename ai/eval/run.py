# ----- analysers -----


def real_analyse() -> tuple[AnalyseFn, dict[str, Any]]:
    """The in-process analysis of the AI service (real models)."""
    from app.analysis import scoring
    from app.analysis.models import AnalyseRequest
    from app.analysis.service import analyse

    def call(request: dict[str, Any], now: datetime) -> dict[str, Any]:
        response = analyse(AnalyseRequest.model_validate(request), now=now)
        return response.model_dump(by_alias=True, mode="json")

    config = {
        "levels": {
            "high": scoring.THRESHOLDS.level_high,
            "medium": scoring.THRESHOLDS.level_medium,
        },
        "weights": dict(scoring.WEIGHTS),
        "thresholds": asdict(scoring.THRESHOLDS),
    }
    return call, config


def stub_analyse() -> tuple[AnalyseFn, dict[str, Any]]:
    """A crude stand-in that follows the contract shape. Only for testing this runner."""
    weights = {sid: 0 for sid in SIGNAL_IDS}
    weights.update(domain_similarity=25, credential_form=10, new_domain=5)

    def call(request: dict[str, Any], _now: datetime) -> dict[str, Any]:
        candidate = request["candidate"]
        page = candidate["page"]
        domain = candidate["domainScore"] / 100
        signals = [
            {
                "id": "domain_similarity",
                "label": "Domain name",
                "value": domain,
                "points": int(25 * domain),
                "maxPoints": 25,
                "detail": "stub",
            },
        ]
        unavailable = ["logo_match", "text_similarity", "brand_mention", "payment_form"]
        if page is None:
            unavailable += ["credential_form", "new_certificate"]
        else:
            has_pw = page["forms"]["hasPasswordField"]
            signals.append(
                {
                    "id": "credential_form",
                    "label": "Password",
                    "value": float(has_pw),
                    "points": 10 if has_pw and domain >= 0.7 else 0,
                    "maxPoints": 10,
                    "detail": "stub",
                }
            )
        score = min(100, sum(s["points"] for s in signals))
        level = "high" if score >= 70 else "medium" if score >= 40 else "low"
        return {
            "modelVersion": "stub",
            "score": score,
            "level": level,
            "signals": signals,
            "reasons": [],
            "unavailable": unavailable,
            "ocrText": "",
            "logoMatch": None,
            "models": {"text": "stub", "image": "stub", "ocr": "stub"},
        }

    return call, {"levels": {"high": 70, "medium": 40}, "weights": weights, "thresholds": {}}


# ----- running -----


def run_cases(
    analyse_fn: AnalyseFn,
    cases: list[dict[str, Any]],
    brands: dict[str, dict[str, Any]],
    now: datetime,
) -> list[dict[str, Any]]:
    results = []
    for index, case in enumerate(cases, 1):
        request = build_request(case, brands, now)
        started = time.perf_counter()
        error = None
        try:
            response = analyse_fn(request, now)
        except Exception as exc:  # noqa: BLE001 - one bad case must not stop the run
            response, error = None, f"{type(exc).__name__}: {exc}"[:300]
        elapsed_ms = (time.perf_counter() - started) * 1000
        label = case["label"]
        row: dict[str, Any] = {
            "id": case["id"],
            "brandId": case["brandId"],
            "category": label["category"],
            "difficulty": label["difficulty"],
            "lookalike": label["lookalike"],
            "hasPage": case["candidate"]["page"] is not None,
            "domainScore": case["candidate"]["domainScore"],
            "latencyMs": round(elapsed_ms, 1),
            "error": error,
        }
        if response is not None:
            row.update(
                score=response["score"],
                level=response["level"],
                signals={
                    s["id"]: {"value": s["value"], "points": s["points"], "max": s["maxPoints"]}
                    for s in response["signals"]
                },
                unavailable=response["unavailable"],
                reasons=response["reasons"],
                modelVersion=response["modelVersion"],
                logoMatch=response.get("logoMatch"),
                ocrText=(response.get("ocrText") or "")[:160],
            )
        results.append(row)
        print(
            f"[{index:>3}/{len(cases)}] {case['id']:<42} "
            f"{'ERROR' if error else str(row['score']).rjust(3) + ' ' + row['level']:<10} "
            f"{elapsed_ms:7.0f} ms",
            flush=True,
        )
    return results


# ----- metrics -----


def _classification(rows: list[dict[str, Any]], thresholds: dict[str, int]) -> dict[str, Any]:
    labels = [r["lookalike"] for r in rows]
    scores = [r["score"] for r in rows]
    out: dict[str, Any] = {
        "n": len(rows),
        "positives": sum(labels),
        "negatives": len(labels) - sum(labels),
        "auc": metrics.roc_auc(labels, scores),
    }
    for name, threshold in thresholds.items():
        out[name] = metrics.evaluate_threshold(labels, scores, threshold)
    return out


def _signal_metrics(rows: list[dict[str, Any]]) -> dict[str, Any]:
    out = {}
    for sid in SIGNAL_IDS:
        present = [r for r in rows if sid in r["signals"]]
        labels = [r["lookalike"] for r in present]
        points = [r["signals"][sid]["points"] for r in present]
        values = [r["signals"][sid]["value"] for r in present]
        fires = [p > 0 for p in points]
        counts = metrics.confusion(labels, fires)
        pos = [p for p, label in zip(points, labels, strict=True) if label]
        neg = [p for p, label in zip(points, labels, strict=True) if not label]
        out[sid] = {
            "n": len(present),
            "unavailable": len(rows) - len(present),
            "aucPoints": metrics.roc_auc(labels, points),
            "aucValue": metrics.roc_auc(labels, values),
            "fires": sum(fires),
            "meanPointsLookalike": sum(pos) / len(pos) if pos else None,
            "meanPointsBenign": sum(neg) / len(neg) if neg else None,
            **counts,
            **metrics.precision_recall_f1(counts),
        }
    return out


def _ablation(rows: list[dict[str, Any]], thresholds: dict[str, int]) -> list[dict[str, Any]]:
    """Score again with one signal's points removed (no model re-run needed)."""
    labels = [r["lookalike"] for r in rows]
    out = []
    for removed in [None, *SIGNAL_IDS]:
        scores = [
            min(
                100,
                sum(s["points"] for sid, s in r["signals"].items() if sid != removed),
            )
            for r in rows
        ]
        sweep = metrics.threshold_sweep(labels, scores, list(range(5, 100, 5)))
        row = {
            "removed": removed,
            "auc": metrics.roc_auc(labels, scores),
            "bestF1": metrics.best_f1_threshold(sweep),
        }
        for name, threshold in thresholds.items():
            row[name] = metrics.evaluate_threshold(labels, scores, threshold)
        out.append(row)
    return out


def _rescore(row: dict[str, Any], weights: dict[str, int]) -> int:
    """Approximate score under other weights: keep each signal's share of its maximum."""
    total = 0
    for sid, signal in row["signals"].items():
        share = signal["points"] / signal["max"] if signal["max"] else 0.0
        total += int(weights[sid] * share + 1e-9)
    return min(100, total)


def _what_if(
    rows: list[dict[str, Any]], current: dict[str, int], thresholds: dict[str, int]
) -> list[dict[str, Any]]:
    labels = [r["lookalike"] for r in rows]
    out = []
    scenarios = {"current weights": current, **WHAT_IF_WEIGHTS}
    for name, weights in scenarios.items():
        scores = [_rescore(r, weights) for r in rows]
        entry: dict[str, Any] = {
            "name": name,
            "weights": weights,
            "auc": metrics.roc_auc(labels, scores),
            "highestBenign": max(
                (s for s, label in zip(scores, labels, strict=True) if not label), default=None
            ),
        }
        for level, threshold in thresholds.items():
            entry[level] = metrics.evaluate_threshold(labels, scores, threshold)
        out.append(entry)
    return out


def _case_summary(row: dict[str, Any]) -> dict[str, Any]:
    fired = sorted(
        ((sid, s["points"]) for sid, s in row["signals"].items() if s["points"] > 0),
        key=lambda item: -item[1],
    )
    return {
        "id": row["id"],
        "category": row["category"],
        "score": row["score"],
        "level": row["level"],
        "domainScore": row["domainScore"],
        "points": {sid: pts for sid, pts in fired},
        "ocrText": row.get("ocrText", ""),
    }


def compute_report(
    results: list[dict[str, Any]], config: dict[str, Any], now: datetime
) -> dict[str, Any]:
    ok = [r for r in results if r["error"] is None]
    levels = config["levels"]
    thresholds = {"medium": levels["medium"], "high": levels["high"]}

    labels = [r["lookalike"] for r in ok]
    scores = [r["score"] for r in ok]
    sweep = metrics.threshold_sweep(labels, scores, list(range(5, 100, 5)))

    subsets = {
        "all": ok,
        "withPage": [r for r in ok if r["hasPage"]],
        "domainOnly": [r for r in ok if not r["hasPage"]],
        "gated": [r for r in ok if r["domainScore"] >= GATE_DOMAIN_SCORE],
        "gatedWithPage": [r for r in ok if r["hasPage"] and r["domainScore"] >= GATE_DOMAIN_SCORE],
    }
    classification = {name: _classification(rows, thresholds) for name, rows in subsets.items()}

    # The Phase 5 name-only rule for comparison: flag when the name score reaches 65.
    base_scores = [r["domainScore"] for r in ok]
    baseline = {
        "auc": metrics.roc_auc(labels, base_scores),
        "threshold65": metrics.evaluate_threshold(labels, base_scores, GATE_DOMAIN_SCORE),
    }

    by_category: dict[str, dict[str, Any]] = {}
    for category in sorted({r["category"] for r in ok}):
        rows = [r for r in ok if r["category"] == category]
        sc = [r["score"] for r in rows]
        by_category[category] = {
            "n": len(rows),
            "lookalike": rows[0]["lookalike"],
            "meanScore": sum(sc) / len(sc),
            "minScore": min(sc),
            "maxScore": max(sc),
            "flaggedMedium": sum(s >= thresholds["medium"] for s in sc),
            "flaggedHigh": sum(s >= thresholds["high"] for s in sc),
        }
    by_difficulty: dict[str, dict[str, Any]] = {}
    for difficulty in ("easy", "medium", "hard"):
        for lookalike in (True, False):
            rows = [r for r in ok if r["difficulty"] == difficulty and r["lookalike"] == lookalike]
            if rows:
                sc = [r["score"] for r in rows]
                by_difficulty[f"{difficulty}/{'lookalike' if lookalike else 'benign'}"] = {
                    "n": len(rows),
                    "flaggedMedium": sum(s >= thresholds["medium"] for s in sc),
                    "flaggedHigh": sum(s >= thresholds["high"] for s in sc),
                    "meanScore": sum(sc) / len(sc),
                }

    distribution = {
        name: {
            **metrics.distribution([r["score"] for r in ok if r["lookalike"] == flag]),
            "histogram": metrics.histogram([r["score"] for r in ok if r["lookalike"] == flag]),
        }
        for name, flag in (("lookalike", True), ("benign", False))
    }

    mistakes: dict[str, Any] = {}
    for name, threshold in thresholds.items():
        fp = [r for r in ok if not r["lookalike"] and r["score"] >= threshold]
        fn = [r for r in ok if r["lookalike"] and r["score"] < threshold]
        mistakes[name] = {
            "falsePositives": [_case_summary(r) for r in sorted(fp, key=lambda r: -r["score"])],
            "falseNegatives": [_case_summary(r) for r in sorted(fn, key=lambda r: r["score"])],
        }

    page_rows = [r for r in ok if r["hasPage"]]
    first = results[0]["latencyMs"] if results else None
    warm = [r["latencyMs"] for r in results[1:]]
    latency = {
        "firstCallMs": first,
        "warmAll": metrics.latency_summary(warm),
        "warmWithPage": metrics.latency_summary(
            [r["latencyMs"] for r in page_rows if r is not results[0]]
        ),
        "warmDomainOnly": metrics.latency_summary(
            [r["latencyMs"] for r in ok if not r["hasPage"] and r is not results[0]]
        ),
    }

    version = next((r.get("modelVersion") for r in ok if r.get("modelVersion")), None)
    return {
        "generatedAt": now.strftime("%Y-%m-%d %H:%M UTC"),
        "modelVersion": version,
        "python": platform.python_version(),
        "config": config,
        "gateDomainScore": GATE_DOMAIN_SCORE,
        "counts": {
            "cases": len(results),
            "errors": [r["id"] for r in results if r["error"]],
            "lookalike": sum(labels),
            "benign": len(labels) - sum(labels),
            "withPage": len(page_rows),
            "domainOnly": len(ok) - len(page_rows),
        },
        "classification": classification,
        "baselineDomainOnly": baseline,
        "perSignal": {
            "withPage": _signal_metrics(subsets["withPage"]),
            "gatedWithPage": _signal_metrics(subsets["gatedWithPage"]),
        },
        "byCategory": by_category,
        "byDifficulty": by_difficulty,
        "scoreDistribution": distribution,
        "sweep": sweep,
        "bestF1": metrics.best_f1_threshold(sweep),
        "ablation": {
            "withPage": _ablation(subsets["withPage"], thresholds),
            "gatedWithPage": _ablation(subsets["gatedWithPage"], thresholds),
        },
        "whatIf": {
            "withPage": _what_if(subsets["withPage"], config["weights"], thresholds),
            "gatedWithPage": _what_if(subsets["gatedWithPage"], config["weights"], thresholds),
        },
        "mistakes": mistakes,
        "latency": latency,
        "cases": results,
    }


# ----- markdown for docs/EVALUATION.md -----


def _f(value: float | None, digits: int = 2) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def _best_text(best: dict[str, Any] | None) -> str:
    return "n/a" if not best else f"{_f(best['f1'])} @ {int(best['threshold'])}"


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(header: list[str], rows: list[list[str]], align_right_from: int = 1) -> list[str]:
    sep = [":---" if i < align_right_from else "---:" for i in range(len(header))]
    return [_row(header), _row(sep), *[_row(r) for r in rows]]


def _cls_row(name: str, block: dict[str, Any], level: str) -> list[str]:
    m = block[level]
    return [
        name,
        f"{block['n']} ({block['positives']}/{block['negatives']})",
        f"{m['tp']}/{m['fp']}/{m['fn']}/{m['tn']}",
        _f(m["precision"]),
        _f(m["recall"]),
        _f(m["f1"]),
        _f(block["auc"]),
    ]


